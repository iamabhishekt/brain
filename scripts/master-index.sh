#!/usr/bin/env bash
# ==============================================================================
# master-index.sh — Generate One-View Task Index Across All Projects
# ==============================================================================
# Scans ~/brain/projects/*/task-board.md and emits a single index file:
#   ~/brain/projects/TASK-INDEX.md
#
# Usage:
#   bash ~/brain/scripts/master-index.sh           # write to brain/projects/TASK-INDEX.md
#   bash ~/brain/scripts/master-index.sh --print    # print to stdout only
# ==============================================================================

set -euo pipefail

BRAIN_DIR="$HOME/brain"
PROJECTS_DIR="$BRAIN_DIR/projects"
OUT="${1:-$PROJECTS_DIR/TASK-INDEX.md}"
if [ "$OUT" = "--print" ]; then OUT="/dev/stdout"; fi

now="$(date '+%Y-%m-%d %H:%M %Z')"

real_projects=()
auto_projects=()

for d in "$PROJECTS_DIR"/*/; do
  [ -d "$d" ] || continue
  name="$(basename "$d")"
  tb="$d/task-board.md"
  [ -f "$tb" ] || continue
  lines=$(wc -l < "$tb" 2>/dev/null || echo 0)
  if [ "$lines" -gt 12 ]; then
    real_projects+=("$name")
  else
    auto_projects+=("$name")
  fi
done

{
  echo "# Master Task Index — All Projects"
  echo ""
  echo "Auto-generated by \`master-index.sh\`. Last refreshed: $now"
  echo ""
  echo "## Legend"
  echo "- **REAL** — substantive task board (hand-curated work items)"
  echo "- **AUTO** — auto-discovered stub (\`- [ ] Initial review\`); no tracked work yet"
  echo ""
  echo "## Active / Real Projects"
  echo ""

  if [ "${#real_projects[@]}" -eq 0 ]; then
    echo "_(none yet — add real task items to a project's task-board.md to surface it here.)_"
    echo ""
  else
    for name in "${real_projects[@]}"; do
      echo "### $name"
      echo ""
      sed -n '1,25p' "$PROJECTS_DIR/$name/task-board.md"
      echo ""
    done
  fi

  echo "## Auto-Discovered Projects (awaiting review)"
  echo ""
  echo "Registered by \`scan-my-repos.sh\` from GitHub. Each has a placeholder task board; add real items as you start work."
  echo ""
  for name in "${auto_projects[@]}"; do
    printf -- '- `%s`\n' "$name"
  done
  echo ""
  echo "**Total auto-discovered:** ${#auto_projects[@]}  |  **Total projects tracked:** $(( ${#real_projects[@]} + ${#auto_projects[@]} ))"
} > "$OUT"

if [ "$OUT" != "/dev/stdout" ]; then
  echo "✓ Wrote master index to $OUT"
fi